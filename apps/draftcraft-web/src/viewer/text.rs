/// Every language, by its primary subtag (`de` in `de-AT`): the full app's languages.
const LANGUAGES: [(&str, &Words); 18] = [
    ("en", &EN),
    ("it", &IT),
    ("de", &DE),
    ("es", &ES),
    ("fr", &FR),
    ("pt", &PT_BR),
    ("ru", &RU),
    ("uk", &UK),
    ("zh", &ZH),
    ("ko", &KO),
    ("ar", &AR),
    ("tr", &TR),
    ("el", &EL),
    ("cs", &CS),
    ("hu", &HU),
    ("sv", &SV),
    ("bs", &BS),
    ("vi", &VI),
];

/// The words for the browser's preferred languages (`navigator.languages`, best first): the first
/// one the viewer speaks, English when it speaks none of them. Any Portuguese gets Brazilian
/// Portuguese, any Chinese simplified Chinese, Croatian and Serbian (Latin) the Bosnian table.
pub fn pick(languages: &[String]) -> &'static Words {
    for l in languages {
        let l = l.to_ascii_lowercase();
        let primary = l.split(['-', '_']).next().unwrap_or_default();
        let primary = match primary {
            "hr" => "bs",
            "sr" if l.contains("latn") => "bs",
            other => other,
        };
        if let Some((_, words)) = LANGUAGES.iter().find(|(code, _)| *code == primary) {
            return words;
        }
    }
    &EN
}

/// The language a `?lang=xx` in the page address asks for, if any (it goes before the browser's
/// own languages). At most 35 characters (the longest a language tag needs) are kept.
pub fn lang_from_query(query: &str) -> Option<String> {
    query.trim_start_matches('?').split('&').find_map(|p| p.strip_prefix("lang=")).filter(|l| !l.is_empty()).map(|l| l.chars().take(35).collect())
}

