/// Words ready for the interface. egui puts right-to-left text in display order itself but
/// doesn't join Arabic letters, so a right-to-left table (Arabic) is turned, once at start, into
/// what it should show: each letter in its joining form (Unicode presentation forms, which the
/// phone's fonts draw). Its long strings carry their own line breaks, so lines never wrap in the
/// middle of a sentence. Other tables are returned as they are.
pub fn for_display(words: &'static Words) -> &'static Words {
    if !draftcraft_fonts::bidi::has_rtl(words.open) {
        return words;
    }
    Box::leak(Box::new(words.map(&|s| String::leak(joined(s)))))
}

/// `s` with its Arabic letters in their joining forms (lam + alef as one ligature).
fn joined(s: &str) -> String {
    let chars: Vec<char> = s.chars().collect();
    draftcraft_fonts::bidi::presentation_forms(&chars, |_| true).into_iter().map(|(c, _)| c).collect()
}

