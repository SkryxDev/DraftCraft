    fn the_address_can_ask_for_a_language() {
        assert_eq!(lang_from_query("?lang=de").as_deref(), Some("de"));
        assert_eq!(lang_from_query("?sample&lang=zh-CN").as_deref(), Some("zh-CN"));
        assert_eq!(lang_from_query("?sample"), None);
        assert_eq!(lang_from_query("?lang="), None);
        assert_eq!(lang_from_query(""), None);
    }

