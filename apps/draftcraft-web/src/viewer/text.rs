    /// labels stay short enough for a phone.
    #[test]
    fn every_language_is_translated_and_short_where_it_must_be() {
        for (code, w) in LANGUAGES {
            if code != "en" {
                assert_ne!(w.open_hint, EN.open_hint, "{code}");
                assert_ne!(w.drag_hint, EN.drag_hint, "{code}");
            }
            for label in [w.fit, w.layers, w.measure, w.layouts, w.more] {
                assert!(label.chars().count() <= 12, "{code}: {label}");
            }
        }
    }
